# 每条记录的置信度：系统内置基础库统一 0.85；
# 用户自定义条目 0.6、第三方数据源按源文档给定（见 food_service.import_*）。
DEFAULT_CONFIDENCE = 0.85
SOURCE_SYSTEM = "system"


def _calc_kcal(protein: float, fat: float, carb: float, fiber: float) -> float:
    """Atwater 反算热量，保证与三大营养素自洽。"""
    usable_carb = max(carb - fiber, 0.0)
    return round(4 * protein + 9 * fat + 4 * usable_carb + 2 * fiber, 1)


def iter_foods() -> Iterator[Dict[str, Any]]:
    """解析紧凑文本表，产出可直接入库的食物字典。

    Yields:
        dict: name / category / aliases / nutrition per 100g / gi / portions
    """
    for lineno, raw in enumerate(RAW.strip().splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = [p.strip() for p in line.split("|")]
        if len(parts) != 11:
            raise ValueError(f"食物数据第 {lineno} 行字段数应为 11，实际 {len(parts)}：{line}")

        name, cat, p, f, c, fib, na, gi, unit_label, unit_g, aliases = parts
        if cat not in CATEGORIES:
            raise ValueError(f"食物数据第 {lineno} 行分类非法：{cat}（{name}）")

        protein, fat, carb, fiber = float(p), float(f), float(c), float(fib)
        sodium = float(na)
        item = {
            "name": name,
            "category": cat,
            "category_label": CATEGORIES[cat],
            "aliases": aliases or "",
            "calorie": _calc_kcal(protein, fat, carb, fiber),
            "protein": protein,
            "fat": fat,
            "carbohydrate": carb,
            "fiber": fiber,
            # 糖：未提供细分数据的情况下以可利用碳水的 35% 估算，标记为估算值
            "sugar": round(max(carb - fiber, 0.0) * 0.35, 1),
            "sodium": sodium,
            "gi": int(gi) if gi else None,
            "source": SOURCE_SYSTEM,
            "confidence": DEFAULT_CONFIDENCE,
            "portions": [
                {
                    "label": unit_label or "100 克",
                    "grams": int(unit_g) if unit_g else 100,
                    "is_default": True,
                },
                {"label": "100 克", "grams": 100, "is_default": False},
            ],
        }
        yield item


def count() -> int:
    """返回内置条目数量。"""
    return sum(1 for _ in iter_foods())
